$m = new mysqli('127.0.0.1', 'almamed', 'localdev', 'almamed_su_db');
if ($m->connect_error) {
    fwrite(STDERR, "DB connect failed\n");
    exit(1);
}
$m->set_charset('utf8mb4');

$ok = 0;
$skip = 0;
$fail = 0;
foreach ($titles as $id => $meta) {
    $id = (int)$id;
    $meta = trim($meta);
    $len = mb_strlen($meta);
    $st = $m->prepare('SELECT id, title, meta_title, url FROM blog_post WHERE id=?');
    $st->bind_param('i', $id);
    $st->execute();
    $row = $st->get_result()->fetch_assoc();
    $st->close();
    if (!$row) {
        echo "MISS id=$id\n";
        $fail++;
        continue;
    }
    $h1 = htmlspecialchars_decode($row['title'], ENT_QUOTES);
    if ($meta === $h1) {
        echo "SAME_AS_H1 id=$id — rewrite needed\n";
        $fail++;
        continue;
    }
    if ($len > 70) {
        echo "WARN long ($len) id=$id: $meta\n";
    }
    echo sprintf(
        "%s #%d %s\n  H1: %s\n  →  %s (%d)\n",
        $apply ? 'SET' : 'DRY',
        $id,
        $row['url'],
        $h1,
        $meta,
        $len
    );
    if ($apply) {
        $up = $m->prepare('UPDATE blog_post SET meta_title=? WHERE id=?');
        $up->bind_param('si', $meta, $id);
        if (!$up->execute()) {
            echo "FAIL update id=$id: ".$m->error."\n";
            $fail++;
        } else {
            $ok++;
        }
        $up->close();
    } else {
        $ok++;
    }
}

echo "\n".($apply ? "APPLIED" : "DRY-RUN").": ok=$ok fail=$fail skip=$skip of ".count($titles)."\n";
if (!$apply) {
    echo "Re-run with --apply to write DB.\n";
}
